/**
 * Writes `app/Tests/Support/DeviceFixtures.swift`: real device-log entries and pairing strings (real keys, real signatures) for the
 * controller's tests of the devices (device pairing design 3.6, 3.9), which run on a stand-in connection and so cannot ask a link to
 * build them. Fixtures are synthetic in content and faithful in shape. Regenerate with
 *   node test/support/app-device-fixtures.ts > app/Tests/Support/DeviceFixtures.swift
 */
import { createNodePlatform } from "../../src/platform-node/platform.ts";
import {
  buildAdd,
  buildGenesis,
  buildRemove,
  type SignedEntry,
} from "../../src/protocol/device-builders.ts";
import {
  checkDeviceEntry,
  type DeviceKeys,
  type LoggedEntry,
  type PublicKeys,
} from "../../src/protocol/device-log.ts";
import { deviceId } from "../../src/protocol/ids.ts";
import { encodePairingString } from "../../src/protocol/pairing-string.ts";
import type { Bytes } from "../../src/protocol/platform.ts";
import { makeProof } from "../protocol/proof.ts";

const platform = createNodePlatform();
const hex = (b: Bytes) => Buffer.from(b).toString("hex");

function party(label: string) {
  const signing = platform.makeKeyPair(`fixture.${label}.s`, "sign");
  const receiving = platform.makeKeyPair(`fixture.${label}.r`, "receive");
  if (!signing.ok || !receiving.ok) throw new Error("no key pair");
  const keys: PublicKeys = { signing: signing.value, receiving: receiving.value };
  const device: DeviceKeys = { kind: "app", ...keys };
  return {
    sign: `fixture.${label}.s`,
    keys,
    device,
    id: deviceId(platform, keys.signing, keys.receiving),
  };
}

const [F, A, B, X, S, D, R] = ["first", "a", "b", "x", "s", "d", "recovery"].map(party) as [
  ReturnType<typeof party>,
  ReturnType<typeof party>,
  ReturnType<typeof party>,
  ReturnType<typeof party>,
  ReturnType<typeof party>,
  ReturnType<typeof party>,
  ReturnType<typeof party>,
];

function made(log: LoggedEntry[], entry: ReturnType<typeof buildAdd>): SignedEntry {
  if (!entry.ok) throw new Error(`refused: ${entry.error}`);
  const v = checkDeviceEntry(platform, log, entry.value.signed, entry.value.sig);
  if (!v.ok) throw new Error(`log refuses: ${v.rule}`);
  return entry.value;
}
function extend(log: LoggedEntry[], e: SignedEntry): LoggedEntry[] {
  const v = checkDeviceEntry(platform, log, e.signed, e.sig);
  if (!v.ok) throw new Error(`log refuses: ${v.rule}`);
  return [...log, v.value];
}
const genesis = made([], buildGenesis(platform, F.sign, F.device, R.keys));
const L1 = extend([], genesis);
const person = genesis.id;
const proofFor = (p: ReturnType<typeof party>, who: Bytes = person) =>
  makeProof(platform, p.sign, who, p.device);
const proofs = { a: proofFor(A), b: proofFor(B), x: proofFor(X), s: proofFor(S) };
const addA1 = made(L1, buildAdd(platform, F.sign, L1, F.id, A.device, proofs.a));
const addX1 = made(L1, buildAdd(platform, F.sign, L1, F.id, X.device, proofs.x));
const L2x = extend(L1, addX1);
const addA2 = made(L2x, buildAdd(platform, F.sign, L2x, F.id, A.device, proofs.a));
const L2 = extend(L1, addA1);
const addB2 = made(L2, buildAdd(platform, F.sign, L2, F.id, B.device, proofs.b));
const L3 = extend(L2, addB2);
const remA3 = made(L3, buildRemove(platform, F.sign, L3, F.id, A.id));
const remB3 = made(L3, buildRemove(platform, F.sign, L3, F.id, B.id));
const remA4 = made(extend(L3, remB3), buildRemove(platform, F.sign, extend(L3, remB3), F.id, A.id));
const remB4 = made(extend(L3, remA3), buildRemove(platform, F.sign, extend(L3, remA3), F.id, B.id));
const addS3 = made(L3, buildAdd(platform, F.sign, L3, F.id, S.device, proofs.s));

const entry = (name: string, e: SignedEntry) =>
  `    static let ${name} = Entry(signed: "${hex(e.signed)}", sig: "${hex(e.sig)}", id: "${hex(e.id)}")`;
const str = (name: string, p: ReturnType<typeof party>, proof: Bytes, label: string) =>
  `    static let ${name} = "${encodePairingString(platform, p.device, proof, label)}"`;
const id = (name: string, p: ReturnType<typeof party>) => `    static let ${name} = "${hex(p.id)}"`;
const raw = (p: ReturnType<typeof party>, proof: Bytes, name: Uint8Array) =>
  `${encodePairingString(platform, p.device, proof, "x").slice(0, -2)}${hex(name)}`;

